CREATE TABLE tenants (
    tenant_id TEXT PRIMARY KEY,
    max_concurrent_calls INTEGER NOT NULL CHECK (max_concurrent_calls > 0)
);

CREATE TABLE campaigns (
    campaign_id TEXT PRIMARY KEY,
    tenant_id TEXT NOT NULL REFERENCES tenants(tenant_id),
    window_start TEXT NOT NULL,
    window_end TEXT NOT NULL,
    window_days_json TEXT,
    max_attempts INTEGER NOT NULL CHECK (max_attempts > 0)
);

CREATE TABLE leads (
    campaign_id TEXT NOT NULL REFERENCES campaigns(campaign_id),
    lead_id TEXT NOT NULL,
    phone_ciphertext BYTEA NOT NULL,
    phone_token TEXT NOT NULL,
    customer_name_ciphertext BYTEA NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN (
        'pending', 'dialing', 'retry_wait', 'callback_wait',
        'completed', 'exhausted', 'dnd_blocked'
    )),
    next_eligible_at TIMESTAMPTZ,
    last_status TEXT,
    last_disposition TEXT,
    last_ended_at TIMESTAMPTZ,
    callback_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (campaign_id, lead_id)
);
CREATE INDEX idx_leads_dispatch
    ON leads(state, next_eligible_at, campaign_id, lead_id);
CREATE INDEX idx_leads_callback
    ON leads(state, callback_at) WHERE state = 'callback_wait';
CREATE INDEX idx_leads_phone_token ON leads(phone_token);

CREATE TABLE attempts (
    attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id TEXT NOT NULL,
    lead_id TEXT NOT NULL,
    tenant_id TEXT NOT NULL REFERENCES tenants(tenant_id),
    phone_ciphertext BYTEA NOT NULL,
    phone_token TEXT NOT NULL,
    attempt_no INTEGER NOT NULL CHECK (attempt_no > 0),
    request_id TEXT NOT NULL UNIQUE,
    call_sid TEXT UNIQUE,
    state TEXT NOT NULL CHECK (state IN (
        'prepared', 'requesting', 'unknown', 'accepted', 'ended', 'retryable'
    )),
    previous_lead_state TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    status TEXT,
    disposition TEXT,
    callback_at TIMESTAMPTZ,
    result_json JSONB,
    last_error TEXT,
    transport_retry_at DOUBLE PRECISION,
    updated_real_at DOUBLE PRECISION NOT NULL DEFAULT 0,
    UNIQUE (campaign_id, lead_id, attempt_no),
    FOREIGN KEY (campaign_id, lead_id) REFERENCES leads(campaign_id, lead_id)
);
CREATE INDEX idx_attempts_lead
    ON attempts(campaign_id, lead_id, attempt_no DESC);
CREATE INDEX idx_attempts_reconcile
    ON attempts(state, updated_at);
CREATE INDEX idx_attempts_tenant_active
    ON attempts(tenant_id, state);
CREATE UNIQUE INDEX uq_active_phone
    ON attempts(phone_token)
    WHERE state IN ('prepared', 'requesting', 'unknown', 'accepted');
CREATE INDEX idx_attempts_active_tenant
    ON attempts(tenant_id) WHERE state IN ('prepared', 'requesting', 'unknown', 'accepted');

-- Per-phone serialization point shared by reservation and result/DND processing.
-- Rows are intentionally retained so a phone cannot race with a new reservation
-- while a prior call's DND result is being committed.
CREATE TABLE phone_guards (
    phone_token TEXT PRIMARY KEY
);

CREATE TABLE dnd_phones (
    phone_token TEXT PRIMARY KEY,
    first_seen_at TIMESTAMPTZ NOT NULL,
    source_request_id TEXT NOT NULL
);

CREATE TABLE webhook_events (
    delivery_id TEXT PRIMARY KEY,
    request_id TEXT NOT NULL REFERENCES attempts(request_id),
    body_sha256 TEXT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_webhook_request ON webhook_events(request_id);

CREATE TABLE app_meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
